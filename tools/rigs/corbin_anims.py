def K(*keys):
    return [[t, v] + ([e] if e else []) for t, v, e in ((k + ("",))[:3] for k in keys)]


def R(*pairs):
    """Raccourci : R((t, r), (t, r, 'o'), …) pour une piste de rotation seule."""
    return K(*[(p[0], {"r": p[1]}) + tuple(p[2:]) for p in pairs])



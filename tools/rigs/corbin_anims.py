def main():
    rig = json.loads(RIG.read_text(encoding="utf-8"))
    head = RIG.read_text(encoding="utf-8").split(' "anims":')[0]
    blocks = []
    for n, a in ANIMS.items():
        h = '  %s: {"dur": %s%s, "keys": {' % (json.dumps(n), a["dur"], ', "loop": true' if a.get("loop") else "")
        body = ',\n'.join('   %s: %s' % (json.dumps(b), json.dumps(v)) for b, v in a["keys"].items())
        blocks.append(h + '\n' + body + '\n  }}')
    RIG.write_text(head + ' "anims": {\n' + ',\n'.join(blocks) + '\n },\n "alias": {"3": "secret", "4": "secret", "5": "secret"}\n}\n',
                   encoding="utf-8")
    json.loads(RIG.read_text(encoding="utf-8"))
    print("ok", len(ANIMS), "animations,", len(rig["parts"]), "pièces")


if __name__ == "__main__":
    main()
